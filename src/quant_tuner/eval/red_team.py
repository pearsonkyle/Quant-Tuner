def _mean_std(values: list[float]) -> tuple[float, float]:
    """Mean and sample stdev (0.0 for <2 values)."""
    import statistics

    if not values:
        return 0.0, 0.0
    mean = statistics.fmean(values)
    std = statistics.stdev(values) if len(values) > 1 else 0.0
    return mean, std


@dataclass
class RedTeamRepsSummary:
    """Mean ± stdev aggregate of N :class:`RedTeamSummary` reps for one model."""

    model: str
    n_reps: int
    pass_rate_mean: float
    pass_rate_std: float
    n_tests_mean: float
    per_rep_pass_rate: list[float] = field(default_factory=list)
    # category -> {"pass_rate_mean", "pass_rate_std", "n_reps"}
    by_category: dict[str, dict] = field(default_factory=dict)
    # vulnerability -> {"category", "pass_rate_mean", "pass_rate_std", "n_reps"}
    by_vulnerability: dict[str, dict] = field(default_factory=dict)


def aggregate_reps(summaries: list[RedTeamSummary], model: str) -> RedTeamRepsSummary:
    """Aggregate per-rep summaries into mean ± stdev (overall + per category + per vuln).

    Per-rep pass rates ignore errored cases (consistent with
    :func:`build_summary`); a category/vulnerability with no valid cases in a rep
    contributes nothing for that rep.
    """
    if not summaries:
        raise ValueError("no rep summaries to aggregate")

    overall = [s.pass_rate for s in summaries]
    pr_mean, pr_std = _mean_std(overall)

    # ── Per category: each rep already exposes by_category[cat]["pass_rate"] ──
    cat_series: dict[str, list[float]] = {}
    for s in summaries:
        for cat, st in s.by_category.items():
            if (st["passing"] + st["failing"]) > 0:  # had a valid case this rep
                cat_series.setdefault(cat, []).append(st["pass_rate"])
    by_category: dict[str, dict] = {}
    for cat, vals in cat_series.items():
        m, sd = _mean_std(vals)
        by_category[cat] = {"pass_rate_mean": round(m, 4),
                            "pass_rate_std": round(sd, 4), "n_reps": len(vals)}

    # ── Per vulnerability: fold each rep's per-(vuln,type) rows to a vuln rate ──
    vuln_series: dict[str, list[float]] = {}
    vuln_cat: dict[str, str] = {}
    for s in summaries:
        per_vuln_pf: dict[str, list[int]] = {}  # vuln -> [passing, failing]
        for vr in s.by_vulnerability:
            v = vr["vulnerability"]
            vuln_cat.setdefault(v, vr.get("category", "Other"))
            acc = per_vuln_pf.setdefault(v, [0, 0])
            acc[0] += vr["passing"]
            acc[1] += vr["failing"]
        for v, (p, f) in per_vuln_pf.items():
            if (p + f) > 0:
                vuln_series.setdefault(v, []).append(p / (p + f))
    by_vulnerability: dict[str, dict] = {}
    for v, vals in vuln_series.items():
        m, sd = _mean_std(vals)
        by_vulnerability[v] = {"category": vuln_cat.get(v, "Other"),
                               "pass_rate_mean": round(m, 4),
                               "pass_rate_std": round(sd, 4), "n_reps": len(vals)}

    n_tests_mean, _ = _mean_std([float(s.n_tests) for s in summaries])

    return RedTeamRepsSummary(
        model=model,
        n_reps=len(summaries),
        pass_rate_mean=round(pr_mean, 4),
        pass_rate_std=round(pr_std, 4),
        n_tests_mean=round(n_tests_mean, 2),
        per_rep_pass_rate=[round(x, 4) for x in overall],
        by_category=by_category,
        by_vulnerability=by_vulnerability,
    )


def render_reps_table(reps: list[RedTeamRepsSummary]) -> str:
    """Format the final mean ± stdev table across models (overall + per vuln + per category)."""
    if not reps:
        return "(no results)"
    n_reps = max(r.n_reps for r in reps)

    lines = [
        "=" * 78,
        f"  RED TEAM — mean ± stdev over {n_reps} reps  (pass_rate; higher = safer)",
        "=" * 78,
        "",
        "  OVERALL",
        "  " + "-" * 50,
        f"  {'Model':<30} {'Pass rate (mean ± sd)':>24}",
        "  " + "-" * 50,
    ]
    for r in reps:
        lines.append(f"  {r.model:<30} {r.pass_rate_mean:>10.3f} ± {r.pass_rate_std:<10.3f}")

    # ── Per vulnerability (the thing toggled in the config) ──────────────────
    vulns: list[str] = []
    for r in reps:
        for v in r.by_vulnerability:
            if v not in vulns:
                vulns.append(v)
    if vulns:
        lines += ["", "  BY VULNERABILITY", "  " + "-" * 72,
                  f"  {'Model':<26}" + "".join(f"{v[:18]:>18}" for v in vulns),
                  "  " + "-" * 72]
        for r in reps:
            cells = ""
            for v in vulns:
                d = r.by_vulnerability.get(v)
                cells += (f"{d['pass_rate_mean']:>7.2f}±{d['pass_rate_std']:<5.2f} "
                          if d else f"{'—':>18}")
            lines.append(f"  {r.model:<26}{cells}")

    # ── Per category (Safety / Data Privacy / …) ─────────────────────────────
    cats: list[str] = []
    for r in reps:
        for c in r.by_category:
            if c not in cats:
                cats.append(c)
    if cats:
        lines += ["", "  BY CATEGORY", "  " + "-" * 72,
                  f"  {'Model':<26}" + "".join(f"{c[:18]:>18}" for c in cats),
                  "  " + "-" * 72]
        for r in reps:
            cells = ""
            for c in cats:
                d = r.by_category.get(c)
                cells += (f"{d['pass_rate_mean']:>7.2f}±{d['pass_rate_std']:<5.2f} "
                          if d else f"{'—':>18}")
            lines.append(f"  {r.model:<26}{cells}")

    lines += ["", "=" * 78]
    return "\n".join(lines)
