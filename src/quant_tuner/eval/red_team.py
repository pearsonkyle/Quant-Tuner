# ── Config resolution ─────────────────────────────────────────────────────────


def resolve_red_team_config(name_or_path: str | Path) -> Path:
    """Allow ``--config red_team_minimal`` (bare name) as well as a real path.

    Bare names resolve against the packaged ``red_team_configs/`` directory.
    """
    path = Path(name_or_path)
    if path.exists():
        return path
    candidate = _PACKAGED_CONFIGS / path.name
    if candidate.exists():
        return candidate
    candidate = _PACKAGED_CONFIGS / f"{path.name}.yaml"
    if candidate.exists():
        return candidate
    raise FileNotFoundError(f"red-team config not found: {name_or_path}")


def load_red_team_config(config: str | Path | dict) -> dict:
    """Return the config as a dict, resolving + loading YAML if needed."""
    if isinstance(config, dict):
        return config
    with open(resolve_red_team_config(config)) as f:
        return yaml.safe_load(f)


# ── deepteam model wrapper for the simulator + judge ──────────────────────────


class LocalLLM(DeepEvalBaseLLM):
    """Wraps an OpenAI-compatible endpoint (local GGUF *or* enterprise API).

    * ``schema`` kwarg -> raises ``TypeError`` so deepteam uses its raw-text +
      ``trimAndLoadJson`` fallback (required for non-native models).
    * ``<think>``/``<thinking>`` blocks are stripped from every response.
    """

    def __init__(
        self,
        model: str,
        base_url: str,
        api_key: str = "sk-no-key-required",
        max_tokens: int = 8192,
        extra_body: dict[str, Any] | None = None,
        timeout: float = 600.0,
    ):
        self._model = model
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        # Generous default: the simulator must emit a full JSON array of attack
        # prompts, and reasoning models (minimax, qwen, deepseek) spend tokens on
        # a thinking pass first. Too low a cap → empty/truncated `content` →
        # deepteam's trimAndLoadJson raises "invalid JSON".
        self.max_tokens = max_tokens
        # Forwarded into every request body (merged at top level by the OpenAI
        # client). Use it to pass llama.cpp's per-request ``chat_template_kwargs``
        # — e.g. ``{"chat_template_kwargs": {"enable_thinking": False}}`` to turn
        # OFF a reasoning model's thinking pass. With thinking on, a single
        # judge/simulator call burns ~700+ tokens on reasoning (minutes on a slow
        # endpoint); off, it answers in tens of tokens.
        self.extra_body = extra_body or None
        self.client = openai.AsyncOpenAI(
            api_key=api_key,
            base_url=self.base_url,
            timeout=timeout,
        )
        super().__init__(model)

    def load_model(self) -> LocalLLM:
        return self

    def generate(self, prompt: str, schema: Any = None, **kwargs: Any) -> str:
        if schema is not None:
            raise TypeError(
                f"{self.get_model_name()} does not support schema parameter"
            )
        # deepteam may call this from inside a running event loop.
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = None

        if loop and loop.is_running():
            import concurrent.futures

            with concurrent.futures.ThreadPoolExecutor() as pool:
                return pool.submit(asyncio.run, self.a_generate(prompt)).result()
        return asyncio.run(self.a_generate(prompt))

    async def a_generate(self, prompt: str, schema: Any = None, **kwargs: Any) -> str:
        if schema is not None:
            raise TypeError(
                f"{self.get_model_name()} does not support schema parameter"
            )
        resp = await self.client.chat.completions.create(
            model=self._model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=self.max_tokens,
            extra_body=self.extra_body,
        )
        return _strip_thinking(resp.choices[0].message.content)

    def get_model_name(self) -> str:
        return self._model


# ── Build helpers ─────────────────────────────────────────────────────────────


def _chat_template_extra_body(
    chat_template_kwargs: dict | str | None,
) -> dict[str, Any] | None:
    """Wrap ``chat_template_kwargs`` into a request ``extra_body`` for LocalLLM.

    Accepts a dict or a JSON string (CLI-friendly). Returns ``None`` when unset,
    so callers can pass it through unconditionally. The resulting body forwards
    llama.cpp's per-request ``chat_template_kwargs`` — pass
    ``{"enable_thinking": False}`` to disable a reasoning judge/simulator's
    thinking pass.
    """
    if chat_template_kwargs is None:
        return None
    if isinstance(chat_template_kwargs, str):
        import json

        chat_template_kwargs = json.loads(chat_template_kwargs)
    return {"chat_template_kwargs": chat_template_kwargs}


def build_vulnerabilities(cfg: dict) -> list:
    """Instantiate deepteam vulnerability objects from the config dict.

    Each branch is gated behind ``enabled`` and uses ``.get()`` so that a config
    omitting a key simply skips that vulnerability instead of erroring.
    """
    vulns: list = []
    v = cfg.get("vulnerabilities", {}) or {}

    def on(key: str) -> bool:
        return bool((v.get(key) or {}).get("enabled", False))

    def types_of(key: str) -> list:
        return list((v.get(key) or {}).get("types", []) or [])

    # ── Responsible AI ────────────────────────────────────────────────────────
    if on("bias"):
        t = types_of("bias")
        vulns.append(Bias(types=t) if t else Bias())
    if on("fairness"):
        vulns.append(Fairness())
    if on("misinformation"):
        t = types_of("misinformation")
        vulns.append(Misinformation(types=t) if t else Misinformation())
    if on("robustness"):
        t = types_of("robustness")
        vulns.append(Robustness(types=t) if t else Robustness())
    if on("ethics"):
        vulns.append(Ethics())

    # ── Data Privacy ──────────────────────────────────────────────────────────
    if on("pii_leakage"):
        t = types_of("pii_leakage")
        vulns.append(PIILeakage(types=t) if t else PIILeakage())
    if on("prompt_leakage"):
        vulns.append(PromptLeakage())

    # ── Safety ────────────────────────────────────────────────────────────────
    if on("toxicity"):
        t = types_of("toxicity")
        vulns.append(Toxicity(types=t) if t else Toxicity())
    if on("personal_safety"):
        vulns.append(PersonalSafety())
    if on("graphic_content"):
        vulns.append(GraphicContent())
    if on("illegal_activity"):
        vulns.append(IllegalActivity())
    if on("child_protection"):
        vulns.append(ChildProtection())

    return vulns


def build_attacks(cfg: dict) -> list:
    """Instantiate deepteam attack objects from the config dict."""
    attacks: list = []
    a = cfg.get("attacks", {}) or {}

    def on(key: str) -> bool:
        return bool(a.get(key, False))

    # ── Single-turn ───────────────────────────────────────────────────────────
    if on("prompt_injection"):
        attacks.append(PromptInjection())
    if on("leetspeak"):
        attacks.append(Leetspeak())
    if on("rot13"):
        attacks.append(ROT13())
    if on("gray_box"):
        attacks.append(GrayBox())
    if on("roleplay"):
        attacks.append(Roleplay())
    if on("math_problem"):
        attacks.append(MathProblem())
    if on("base64"):
        attacks.append(Base64())
    if on("multilingual"):
        attacks.append(Multilingual())
    if on("emotional_manipulation"):
        attacks.append(EmotionalManipulation())
    if on("authority_escalation"):
        attacks.append(AuthorityEscalation())

    # ── Multi-turn ────────────────────────────────────────────────────────────
    if on("linear_jailbreaking"):
        attacks.append(LinearJailbreaking())
    if on("crescendo_jailbreaking"):
        attacks.append(CrescendoJailbreaking())
    if on("tree_jailbreaking"):
        attacks.append(TreeJailbreaking())

    return attacks


@dataclass
class TargetSampling:
    """Sampling params applied to the *target* (the model under test).

    ``temperature`` / ``top_p`` / ``max_tokens`` are OpenAI-standard and ride as
    native params; ``top_k`` / ``min_p`` / ``repeat_penalty`` are llama.cpp
    extensions forwarded via ``extra_body``. Leave a field ``None`` to let the
    server use its own default. Defaults here are Gemma's documented values
    (``temperature=0.25, top_p=0.95, top_k=20``).
    """

    temperature: float | None = 0.25
    top_p: float | None = 0.95
    top_k: int | None = 20
    min_p: float | None = None
    repeat_penalty: float | None = None
    max_tokens: int | None = None

    def native_kwargs(self) -> dict[str, Any]:
        kw: dict[str, Any] = {}
        if self.temperature is not None:
            kw["temperature"] = self.temperature
        if self.top_p is not None:
            kw["top_p"] = self.top_p
        if self.max_tokens is not None:
            kw["max_tokens"] = self.max_tokens
        return kw

    def extra_body(self) -> dict[str, Any]:
        eb: dict[str, Any] = {}
        if self.top_k is not None:
            eb["top_k"] = self.top_k
        if self.min_p is not None:
            eb["min_p"] = self.min_p
        if self.repeat_penalty is not None:
            eb["repeat_penalty"] = self.repeat_penalty
        return eb


def _make_target_callback(
    base_url: str,
    model: str,
    api_key: str,
    sampling: TargetSampling | None = None,
    timeout: float = 600.0,
):
    """Return an async callback that queries the target model at ``base_url``.

    ``timeout`` defaults to 600s (was 120s): a slow / GPU-contended local target
    answering an attack that elicits a long generation can blow past a tight
    timeout, and deepteam then records the case as an error (``score=None``) —
    which drops it from the denominator and breaks cross-quant comparability.
    Pair a generous timeout with a ``TargetSampling.max_tokens`` cap so no single
    generation can run away.
    """
    client = openai.AsyncOpenAI(api_key=api_key, base_url=base_url.rstrip("/"), timeout=timeout)
    sampling = sampling or TargetSampling()
    native = sampling.native_kwargs()
    extra_body = sampling.extra_body()

    async def _callback(input: str) -> str:
        resp = await client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": input}],
            extra_body=extra_body or None,
            **native,
        )
        return _strip_thinking(resp.choices[0].message.content)

    return _callback


# ── Summary ────────────────────────────────────────────────────────────────────


@dataclass
class RedTeamSummary:
    """Float-metrics bag for a red-team run (mirrors the other eval summaries)."""

    model: str
    n_tests: int
    pass_rate: float
    n_passing: int = 0
    n_failing: int = 0
    n_errored: int = 0
    run_duration_sec: float = 0.0
    by_category: dict[str, dict] = field(default_factory=dict)
    by_vulnerability: list[dict] = field(default_factory=list)
    by_attack: list[dict] = field(default_factory=list)
    failed_cases: list[dict] = field(default_factory=list)


def _vt_value(tc: Any) -> str:
    vt = getattr(tc, "vulnerability_type", None)
    return vt.value if hasattr(vt, "value") else str(vt)


def build_summary(risk_assessment: Any, model: str) -> RedTeamSummary:
    """Convert a deepteam ``risk_assessment`` into a :class:`RedTeamSummary`.

    Counts are derived from ``risk_assessment.test_cases`` (the source of truth),
    NOT from ``overview.vulnerability_type_results`` — the overview aggregates
    silently DROP cases whose ``score is None`` (target-generation errors, judge
    parse failures), so summing them undercounts ``n_tests`` and reports
    ``n_errored == 0`` even when a target timed out on half the bank. Here a case
    with ``score == 1`` is a pass, ``score == 0`` a fail, and ``score is None``
    an error — so ``n_tests`` always equals the full attempted case count and the
    denominator is explicit (essential for a fair cross-quant comparison).
    """
    # ── Per-case rollups (include errored so the denominator is honest) ──────
    def _blank() -> dict[str, int]:
        return {"passing": 0, "failing": 0, "errored": 0}

    cat_stats: dict[str, dict[str, int]] = {}
    vuln_stats: dict[tuple[str, str], dict[str, int]] = {}
    attack_stats: dict[str, dict[str, int]] = {}
    n_passing = n_failing = n_errored = 0

    for tc in risk_assessment.test_cases:
        bucket = "errored" if tc.score is None else ("passing" if tc.score == 1 else "failing")
        if bucket == "passing":
            n_passing += 1
        elif bucket == "failing":
            n_failing += 1
        else:
            n_errored += 1
        cat = CATEGORY_MAP.get(tc.vulnerability, "Other")
        cat_stats.setdefault(cat, _blank())[bucket] += 1
        vkey = (tc.vulnerability, _vt_value(tc))
        vuln_stats.setdefault(vkey, _blank())[bucket] += 1
        am = tc.attack_method or "N/A"
        attack_stats.setdefault(am, _blank())[bucket] += 1

    def _rate(s: dict[str, int]) -> float:
        valid = s["passing"] + s["failing"]
        return round(s["passing"] / valid, 4) if valid else 0.0

    by_category: dict[str, dict] = {}
    for cat, s in cat_stats.items():
        by_category[cat] = {
            "total_tests": s["passing"] + s["failing"] + s["errored"],
            "passing": s["passing"], "failing": s["failing"], "errored": s["errored"],
            "pass_rate": _rate(s),
        }

    by_vulnerability: list[dict] = [
        {
            "vulnerability": v, "type": t,
            "category": CATEGORY_MAP.get(v, "Other"),
            "pass_rate": _rate(s),
            "passing": s["passing"], "failing": s["failing"], "errored": s["errored"],
        }
        for (v, t), s in vuln_stats.items()
    ]

    by_attack: list[dict] = [
        {
            "attack_method": am, "pass_rate": _rate(s),
            "passing": s["passing"], "failing": s["failing"], "errored": s["errored"],
        }
        for am, s in attack_stats.items()
    ]

    failed_cases: list[dict] = []
    for tc in risk_assessment.test_cases:
        if tc.score is not None and tc.score == 0:
            failed_cases.append(
                {
                    "vulnerability": tc.vulnerability,
                    "vulnerability_type": _vt_value(tc),
                    "category": CATEGORY_MAP.get(tc.vulnerability, "Other"),
                    "attack_method": tc.attack_method,
                    "input": tc.input,
                    "actual_output": tc.actual_output,
                    "reason": tc.reason,
                }
            )

    n_tests = n_passing + n_failing + n_errored
    valid = n_passing + n_failing
    pass_rate = round(n_passing / valid, 4) if valid else 0.0

    return RedTeamSummary(
        model=model,
        n_tests=n_tests,
        pass_rate=pass_rate,
        n_passing=n_passing,
        n_failing=n_failing,
        n_errored=n_errored,
        run_duration_sec=round(risk_assessment.overview.run_duration, 2),
        by_category=by_category,
        by_vulnerability=by_vulnerability,
        by_attack=by_attack,
        failed_cases=failed_cases,
    )


# ── Orchestrator ───────────────────────────────────────────────────────────────


def run_red_team_eval(
    config: str | Path | dict,
    *,
    judge_model: str,
    judge_base_url: str,
    simulator_model: str,
    simulator_base_url: str,
    model_path: Path | None = None,
    base_url: str | None = None,
    judge_api_key: str = "sk-no-key-required",
    simulator_api_key: str = "sk-no-key-required",
    judge_chat_template_kwargs: dict | str | None = None,
    simulator_chat_template_kwargs: dict | str | None = None,
    target_model_name: str = "local",
    target_purpose: str | None = None,
    target_sampling: TargetSampling | None = None,
    attacks_per_vulnerability_type: int = 1,
    max_concurrent: int = 4,
    ignore_errors: bool = True,
    model_label: str | None = None,
    ctx: int = 8192,
    ngl: int = 99,
    server_log_path: Path | None = None,
    server_startup_timeout: float = 120.0,
    chat_template_kwargs: str | None = None,
    api_key: str = "sk-no-key-required",
    red_teamer: Any | None = None,
    reuse_simulated_test_cases: bool = False,
    bank_path: Path | None = None,
) -> RedTeamSummary:
    """Run the deepteam red-team suite against a target model.

    Provide exactly one of ``model_path`` (a GGUF — spawned via
    :func:`running_server`) or ``base_url`` (a target already served). The judge
    and simulator are *separate* OpenAI-compatible endpoints.

    **Frozen-bank mode.** Pass a shared :class:`~deepteam.red_teamer.RedTeamer`
    as ``red_teamer`` to reuse one attack bank across many targets: the first
    call (``reuse_simulated_test_cases=False``) simulates + stores the attacks on
    the instance; later calls (``reuse_simulated_test_cases=True``) replay the
    *identical* prompts, so every quant sees the same cases and every category
    gets the same denominator. ``bank_path`` (JSON) dumps the simulated cases
    after the run for inspection / curation. When ``red_teamer`` is ``None`` the
    old behavior holds — a throwaway ``RedTeamer`` per call (fresh attacks).
    """
    if (model_path is None) == (base_url is None):
        raise ValueError("provide exactly one of model_path or base_url")

    cfg = load_red_team_config(config)
    vulnerabilities = build_vulnerabilities(cfg)
    attacks = build_attacks(cfg)
    if not vulnerabilities:
        raise ValueError("config enables no vulnerabilities")

    execution = cfg.get("execution", {}) or {}
    apvt = execution.get("attacks_per_vulnerability_type", attacks_per_vulnerability_type)
    mc = execution.get("max_concurrent", max_concurrent)
    ie = execution.get("ignore_errors", ignore_errors)

    eval_model = LocalLLM(
        model=judge_model,
        base_url=judge_base_url,
        api_key=judge_api_key,
        extra_body=_chat_template_extra_body(judge_chat_template_kwargs),
    )
    sim_model = LocalLLM(
        model=simulator_model,
        base_url=simulator_base_url,
        api_key=simulator_api_key,
        extra_body=_chat_template_extra_body(simulator_chat_template_kwargs),
    )

    label = model_label or (model_path.name if model_path is not None else "remote")

    def _run_against(url: str) -> RedTeamSummary:
        target_callback = _make_target_callback(
            url, target_model_name, api_key, sampling=target_sampling
        )
        if red_teamer is not None:
            # Frozen-bank path: drive the *instance* so its simulated_test_cases
            # persist across targets. red_team()'s own simulator/eval kwargs
            # default to the ones set on the constructor.
            if reuse_simulated_test_cases:
                # deepteam's _a_attack early-returns on a case whose .error is
                # already set — so a case that errored on the SEED target would be
                # permanently skipped for every later target (the monotonic
                # 113→100→97→94 pruning we hit). Reset per-run evaluation state so
                # each target re-probes the *full* frozen bank from scratch; only
                # the simulated .input / .turns (the frozen prompts) are kept.
                _reset_bank_for_reuse(red_teamer)
            risk_assessment = red_teamer.red_team(
                model_callback=target_callback,
                vulnerabilities=vulnerabilities,
                attacks=attacks,
                simulator_model=sim_model,
                evaluation_model=eval_model,
                attacks_per_vulnerability_type=apvt,
                ignore_errors=ie,
                reuse_simulated_test_cases=reuse_simulated_test_cases,
            )
            if bank_path is not None:
                _dump_attack_bank(red_teamer, bank_path)
        else:
            risk_assessment = red_team(
                model_callback=target_callback,
                vulnerabilities=vulnerabilities,
                attacks=attacks,
                simulator_model=sim_model,
                evaluation_model=eval_model,
                attacks_per_vulnerability_type=apvt,
                max_concurrent=mc,
                ignore_errors=ie,
                target_purpose=target_purpose,
            )
        return build_summary(risk_assessment, label)

    if base_url is not None:
        return _run_against(base_url)
    with running_server(
        model_path,
        ctx=ctx,
        ngl=ngl,
        log_path=server_log_path,
        startup_timeout=server_startup_timeout,
        chat_template_kwargs=chat_template_kwargs,
    ) as url:
        return _run_against(url)


def make_red_teamer(
    *,
    simulator_model: Any,
    evaluation_model: Any,
    target_purpose: str | None = None,
    max_concurrent: int = 1,
    async_mode: bool = True,
) -> Any:
    """Build a persistent :class:`~deepteam.red_teamer.RedTeamer`.

    Share one instance across targets and pass it to
    :func:`run_red_team_eval` with ``reuse_simulated_test_cases=True`` on every
    call after the first — that reuses the *same* simulated attack bank so all
    targets are scored on an identical set of prompts.
    """
    from deepteam.red_teamer import RedTeamer

    return RedTeamer(
        simulator_model=simulator_model,
        evaluation_model=evaluation_model,
        target_purpose=target_purpose or "",
        async_mode=async_mode,
        max_concurrent=max_concurrent,
    )


def _reset_bank_for_reuse(red_teamer: Any) -> None:
    """Clear per-target evaluation state on the frozen bank before a reuse run.

    Resets ``score`` / ``reason`` / ``error`` / ``actual_output`` on every
    stored test case so deepteam re-probes + re-judges each one against the new
    target. The simulated ``input`` and multi-turn ``turns`` (the frozen prompts)
    are left intact — that's what makes the bank identical across targets.
    Without this, ``_a_attack``'s ``if test_case.error is not None: return`` short
    -circuits any case that errored on an earlier target, so counts only shrink.
    """
    for tc in getattr(red_teamer, "test_cases", None) or []:
        tc.score = None
        tc.reason = None
        tc.error = None
        tc.actual_output = None


def _dump_attack_bank(red_teamer: Any, bank_path: Path) -> None:
    """Serialize the RedTeamer's simulated attack bank to JSON for curation.

    Captures every simulated case's vulnerability / type / attack method and the
    seed ``input`` (first-turn prompt). Multi-turn follow-ups are adaptive and
    not part of the frozen seed, so only the seed prompt is persisted.
    """
    import json

    cases = getattr(red_teamer, "test_cases", None) or []
    rows = []
    for tc in cases:
        vt = getattr(tc, "vulnerability_type", None)
        rows.append(
            {
                "vulnerability": getattr(tc, "vulnerability", None),
                "vulnerability_type": vt.value if hasattr(vt, "value") else str(vt),
                "attack_method": getattr(tc, "attack_method", None),
                "input": getattr(tc, "input", None),
            }
        )
    bank_path.parent.mkdir(parents=True, exist_ok=True)
    bank_path.write_text(json.dumps({"n_cases": len(rows), "cases": rows}, indent=2))


# ── Renderer ───────────────────────────────────────────────────────────────────


def render_summary(summary: RedTeamSummary, *, max_failed: int = 10) -> str:
    """Format a :class:`RedTeamSummary` for human-readable stdout."""
    lines = [
        "=" * 70,
        "  RED TEAM EVALUATION REPORT",
        "=" * 70,
        f"  Model            : {summary.model}",
        f"  Tests            : {summary.n_tests}  "
        f"(pass {summary.n_passing} / fail {summary.n_failing} / err {summary.n_errored})",
        f"  Overall pass rate: {summary.pass_rate:.3f}",
        f"  Run duration     : {summary.run_duration_sec}s",
        "=" * 70,
        "",
        "  CATEGORY SUMMARY",
        "  " + "-" * 66,
        f"  {'Category':<20} {'Pass Rate':>10} {'Pass':>6} {'Fail':>6} "
        f"{'Error':>6} {'Total':>6}",
        "  " + "-" * 66,
    ]
    for cat in sorted(summary.by_category):
        s = summary.by_category[cat]
        lines.append(
            f"  {cat:<20} {s['pass_rate']:>10.0%} {s['passing']:>6} "
            f"{s['failing']:>6} {s['errored']:>6} {s['total_tests']:>6}"
        )

    if summary.by_attack:
        lines += [
            "",
            "  ATTACK METHOD RESULTS",
            "  " + "-" * 56,
            f"  {'Attack Method':<30} {'Pass Rate':>10} {'Pass':>6} {'Fail':>6}",
            "  " + "-" * 56,
        ]
        for ar in summary.by_attack:
            lines.append(
                f"  {(ar['attack_method'] or 'N/A'):<30} {ar['pass_rate']:>10.0%} "
                f"{ar['passing']:>6} {ar['failing']:>6}"
            )

    if summary.failed_cases:
        shown = summary.failed_cases[:max_failed]
        lines += [
            "",
            f"  FAILED TEST CASES (showing {len(shown)} of {len(summary.failed_cases)})",
            "  " + "-" * 66,
        ]
        for i, tc in enumerate(shown, 1):
            lines.append(f"\n  [{i}] {tc['category']} / {tc['vulnerability']}")
            lines.append(f"      Type   : {tc['vulnerability_type']}")
            lines.append(f"      Attack : {tc['attack_method'] or 'N/A'}")
            lines.append(f"      Input  : {(tc['input'] or '')[:200]}")
            lines.append(f"      Output : {(tc['actual_output'] or '')[:200]}")
            if tc.get("reason"):
                lines.append(f"      Reason : {tc['reason'][:200]}")

    lines += ["", "=" * 70]
    return "\n".join(lines)


# ── Multi-rep aggregation ───────────────────────────────────────────────────────


def _mean_std(values: list[float]) -> tuple[float, float]:
    """Mean and sample stdev (0.0 for <2 values)."""
    import statistics

    if not values:
        return 0.0, 0.0
    mean = statistics.fmean(values)
    std = statistics.stdev(values) if len(values) > 1 else 0.0
    return mean, std


@dataclass
class RedTeamRepsSummary:
    """Mean ± stdev aggregate of N :class:`RedTeamSummary` reps for one model."""

    model: str
    n_reps: int
    pass_rate_mean: float
    pass_rate_std: float
    n_tests_mean: float
    per_rep_pass_rate: list[float] = field(default_factory=list)
    # category -> {"pass_rate_mean", "pass_rate_std", "n_reps"}
    by_category: dict[str, dict] = field(default_factory=dict)
    # vulnerability -> {"category", "pass_rate_mean", "pass_rate_std", "n_reps"}
    by_vulnerability: dict[str, dict] = field(default_factory=dict)


def aggregate_reps(summaries: list[RedTeamSummary], model: str) -> RedTeamRepsSummary:
    """Aggregate per-rep summaries into mean ± stdev (overall + per category + per vuln).

    Per-rep pass rates ignore errored cases (consistent with
    :func:`build_summary`); a category/vulnerability with no valid cases in a rep
    contributes nothing for that rep.
    """
    if not summaries:
        raise ValueError("no rep summaries to aggregate")

    overall = [s.pass_rate for s in summaries]
    pr_mean, pr_std = _mean_std(overall)

    # ── Per category: each rep already exposes by_category[cat]["pass_rate"] ──
    cat_series: dict[str, list[float]] = {}
    for s in summaries:
        for cat, st in s.by_category.items():
            if (st["passing"] + st["failing"]) > 0:  # had a valid case this rep
                cat_series.setdefault(cat, []).append(st["pass_rate"])
    by_category: dict[str, dict] = {}
    for cat, vals in cat_series.items():
        m, sd = _mean_std(vals)
        by_category[cat] = {"pass_rate_mean": round(m, 4),
                            "pass_rate_std": round(sd, 4), "n_reps": len(vals)}

    # ── Per vulnerability: fold each rep's per-(vuln,type) rows to a vuln rate ──
    vuln_series: dict[str, list[float]] = {}
    vuln_cat: dict[str, str] = {}
    for s in summaries:
        per_vuln_pf: dict[str, list[int]] = {}  # vuln -> [passing, failing]
        for vr in s.by_vulnerability:
            v = vr["vulnerability"]
            vuln_cat.setdefault(v, vr.get("category", "Other"))
            acc = per_vuln_pf.setdefault(v, [0, 0])
            acc[0] += vr["passing"]
            acc[1] += vr["failing"]
        for v, (p, f) in per_vuln_pf.items():
            if (p + f) > 0:
                vuln_series.setdefault(v, []).append(p / (p + f))
    by_vulnerability: dict[str, dict] = {}
    for v, vals in vuln_series.items():
        m, sd = _mean_std(vals)
        by_vulnerability[v] = {"category": vuln_cat.get(v, "Other"),
                               "pass_rate_mean": round(m, 4),
                               "pass_rate_std": round(sd, 4), "n_reps": len(vals)}

    n_tests_mean, _ = _mean_std([float(s.n_tests) for s in summaries])

    return RedTeamRepsSummary(
        model=model,
        n_reps=len(summaries),
        pass_rate_mean=round(pr_mean, 4),
        pass_rate_std=round(pr_std, 4),
        n_tests_mean=round(n_tests_mean, 2),
        per_rep_pass_rate=[round(x, 4) for x in overall],
        by_category=by_category,
        by_vulnerability=by_vulnerability,
    )


def render_reps_table(reps: list[RedTeamRepsSummary]) -> str:
    """Format the final mean ± stdev table across models (overall + per vuln + per category)."""
    if not reps:
        return "(no results)"
    n_reps = max(r.n_reps for r in reps)

    lines = [
        "=" * 78,
        f"  RED TEAM — mean ± stdev over {n_reps} reps  (pass_rate; higher = safer)",
        "=" * 78,
        "",
        "  OVERALL",
        "  " + "-" * 50,
        f"  {'Model':<30} {'Pass rate (mean ± sd)':>24}",
        "  " + "-" * 50,
    ]
    for r in reps:
        lines.append(f"  {r.model:<30} {r.pass_rate_mean:>10.3f} ± {r.pass_rate_std:<10.3f}")

    # ── Per vulnerability (the thing toggled in the config) ──────────────────
    vulns: list[str] = []
    for r in reps:
        for v in r.by_vulnerability:
            if v not in vulns:
                vulns.append(v)
    if vulns:
        lines += ["", "  BY VULNERABILITY", "  " + "-" * 72,
                  f"  {'Model':<26}" + "".join(f"{v[:18]:>18}" for v in vulns),
                  "  " + "-" * 72]
        for r in reps:
            cells = ""
            for v in vulns:
                d = r.by_vulnerability.get(v)
                cells += (f"{d['pass_rate_mean']:>7.2f}±{d['pass_rate_std']:<5.2f} "
                          if d else f"{'—':>18}")
            lines.append(f"  {r.model:<26}{cells}")

    # ── Per category (Safety / Data Privacy / …) ─────────────────────────────
    cats: list[str] = []
    for r in reps:
        for c in r.by_category:
            if c not in cats:
                cats.append(c)
    if cats:
        lines += ["", "  BY CATEGORY", "  " + "-" * 72,
                  f"  {'Model':<26}" + "".join(f"{c[:18]:>18}" for c in cats),
                  "  " + "-" * 72]
        for r in reps:
            cells = ""
            for c in cats:
                d = r.by_category.get(c)
                cells += (f"{d['pass_rate_mean']:>7.2f}±{d['pass_rate_std']:<5.2f} "
                          if d else f"{'—':>18}")
            lines.append(f"  {r.model:<26}{cells}")

    lines += ["", "=" * 78]
    return "\n".join(lines)
